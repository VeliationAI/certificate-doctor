from __future__ import annotations

import json
from pathlib import Path

from certificate_doctor.models import CHECK_LABELS, Diagnosis


def to_json(diagnosis: Diagnosis, indent: int = 2) -> str:
    return json.dumps(diagnosis.to_dict(), indent=indent)


def to_markdown(diagnosis: Diagnosis) -> str:
    d = diagnosis
    lines = [
        f"# Certificate Doctor Report — `{d.file_name}`",
        "",
        f"**Score:** {d.overall_score:.0f}/100 · **Verdict:** {d.verdict}",
        f"**Size:** {d.width}×{d.height}px",
        "",
        "> Screening tool with evidence — not court-proof, cannot query university databases, "
        "heavy compression can false-positive, professional forgeries may slip through.",
        "",
        "## Check breakdown",
        "",
        "| Check | Weight | Score | Contribution |",
        "|---|---:|---:|---:|",
    ]
    for c in d.checks:
        label = CHECK_LABELS.get(c.name, c.name)
        lines.append(
            f"| {label} | {c.weight} | {c.score:.0f} | {c.weighted_score:.1f} |"
        )

    lines.extend(["", "## Findings", ""])
    if not d.top_issues:
        lines.append("_No major forensic flags. Still verify through official channels._")
    else:
        for i, issue in enumerate(d.top_issues, 1):
            lines.extend(
                [
                    f"### {i}. {issue.title}",
                    f"- **Check:** {issue.check} · **Severity:** {issue.severity}",
                    f"- **Detail:** {issue.detail}",
                ]
            )
            if issue.evidence:
                lines.append(f"- **Evidence:** `{issue.evidence}`")
            lines.append("")

    if d.overlay_path:
        lines.extend(
            [
                "## Artifacts",
                "",
                f"- Overlay: `{d.overlay_path}`",
                f"- Heatmap: `{d.heatmap_path}`",
                "",
            ]
        )

    lines.extend(
        [
            "## Rubric",
            "",
            "- Error Level Analysis — 30",
            "- Text / font consistency — 25",
            "- Metadata — 15",
            "- Copy-move detection — 15",
            "- Logic checks — 15",
            "",
            "_Generated by Certificate Doctor · Veliation AI · offline-capable core · MIT._",
        ]
    )
    return "\n".join(lines)


def write_reports(diagnosis: Diagnosis, out_dir: str | Path) -> tuple[Path, Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    stem = Path(diagnosis.file_name).stem
    md_path = out / f"{stem}.certificate-doctor.md"
    json_path = out / f"{stem}.certificate-doctor.json"
    md_path.write_text(to_markdown(diagnosis), encoding="utf-8")
    json_path.write_text(to_json(diagnosis), encoding="utf-8")
    return md_path, json_path
